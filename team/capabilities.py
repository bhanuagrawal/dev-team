"""CAPABILITIES — the team's own inventory, checked against one project.

Why this exists (2026-11-05): the polish audit (`ux-plan`/`ux-audit`) landed in
the team as a new COMMAND, not as a new profile key. `adapt` compares data shape
(schema number, key presence), so it reported "up to date with the team" forever
while a project with four finished screens had `targets: []` and could not be
audited at all. The one check that would have said so — `verify`'s "screen
changed, no audit since" warning — had zero surfaces to look at and could not
fire. A capability could therefore land in dev-team and never reach an existing
project: improvement without adoption, silently.

This module is that missing comparison: for every capability the team ships, is
THIS project wired for it? Three properties keep it honest:

  * deterministic — file reads only, no model, no network;
  * presence-driven — a satisfied capability reports "ok" and disappears from
    every report, so nothing accumulates as noise;
  * never silently writes what the owner owns — the declared screens
    (`profile['targets']`) are owner-approved, so the team PROPOSES a draft and
    an ask, and never fills it in behind the owner's back.

Consumers: `adapt` turns each non-ok row into an owner ask (printed by `record`
on every outcome), `doctor` prints the same rows as a WARN, and
`devteam capabilities <project>` shows the whole table on demand.
"""
from __future__ import annotations

from pathlib import Path

from .core import pipeline_dir, profile_of, save_json

DRAFT_NAME = "targets-draft.json"


# --------------------------------------------------------------------------- #
# discovery (offline, local checkout — never the delivery ref: this is about
# what exists on disk right now, not about what shipped)
# --------------------------------------------------------------------------- #
def _composable_files(project: Path, profile: dict) -> list[str]:
    """Source files that actually declare a composable, project-relative.

    Generic by construction: it reads the project's own `src_root` and looks for
    the platform's composable annotation; it names no file, screen or app.
    """
    root = project / str(profile.get("src_root") or ".")
    if not root.is_dir():
        return []
    out: list[str] = []
    for p in sorted(root.rglob("*.kt")):
        parts = set(p.parts)
        if "__pycache__" in parts or "build" in parts or "generated" in parts:
            continue
        try:
            text = p.read_text(errors="ignore")
        except OSError:
            continue
        if "@Composable" in text:
            out.append(p.relative_to(project).as_posix())
    return out


def _declared(profile: dict) -> list[dict]:
    return [t for t in (profile.get("targets") or []) if isinstance(t, dict) and t]


def _draft_rows(files: list[str]) -> list[dict]:
    rows = []
    for f in files:
        rows.append({
            "label": Path(f).stem,
            "paths": [f],
            "risk": "safe",
        })
    return rows


def draft_path(project: Path) -> Path:
    return pipeline_dir(project) / DRAFT_NAME


def write_draft(project: Path, profile: dict) -> Path | None:
    """Write the proposed screen declarations when the project has none.

    A DRAFT, never the profile: `targets` is owner-approved, so the best the team
    may do on its own is put a reviewable file next to the ask. Idempotent — it
    only rewrites when the discovered set actually changed.
    """
    files = _composable_files(project, profile)
    if not files:
        return None
    payload = {
        "_comment": (
            "PROPOSED ONLY — the team never declares a project's screens for its "
            "owner. Review these rows, drop anything that is not a real screen, "
            "then merge them into .pipeline/profile.json['targets'] (same shape). "
            "This file is regenerated by `devteam adapt` and is safe to delete."),
        "targets": _draft_rows(files),
    }
    dest = draft_path(project)
    try:
        import json
        if dest.exists() and json.loads(dest.read_text()) == payload:
            return dest
    except Exception:
        pass
    save_json(dest, payload)
    return dest


# --------------------------------------------------------------------------- #
# the checks
# --------------------------------------------------------------------------- #
def check_polish(project: Path, profile: dict, state: dict) -> dict:
    """Can this project's look and feel be MEASURED at all?

    The polish audit judges screens the profile declares; with none declared it
    has nothing to look at, and "we polished it" can be neither claimed nor
    disproved. Not an error — an unwired capability, owned by the project.
    """
    declared = _declared(profile)
    files = _composable_files(project, profile)
    if not files and not declared:
        return {"status": "n/a",
                "detail": "no composable screens on disk — nothing to polish"}
    if not declared:
        return {"status": "unwired",
                "detail": (f"{len(files)} composable screen(s) on disk, "
                           f"0 declared in profile['targets']")}
    # Declared: does each one have pixels the audit can judge?
    from . import ux_audit
    plan = ux_audit.plan(project)
    if not plan["rows"]:
        # Declared but none resolves to a composable file, in the checkout OR on
        # the delivery ref: the declarations are stale, and the audit would look
        # at nothing while the project read as wired.
        return {"status": "partial",
                "detail": (f"{len(declared)} screen(s) declared, 0 resolve to a "
                           f"composable file (stale paths in profile['targets']?)")}
    no_render = [r["label"] for r in plan["rows"] if not r.get("render")]
    counts = plan["counts"]
    audited = sum(1 for r in plan["rows"] if r.get("audited_at"))
    if no_render:
        return {"status": "partial",
                "detail": (f"{len(declared)} screen(s) declared, "
                           f"{len(no_render)} with no render to audit "
                           f"({', '.join(no_render[:3])})"),
                "counts": counts, "audited": audited}
    # Declared and rendered is not the same as MEASURED: until a reaction exists,
    # "we polished it" is still unverifiable, so the capability stays unwired and
    # one `ux-audit` clears it. Otherwise a project reads green with zero evidence.
    never = [r["label"] for r in plan["rows"] if not r.get("audited_at")]
    if never:
        return {"status": "partial",
                "detail": (f"{len(declared)} screen(s) declared and rendered, "
                           f"{len(never)} never reacted to "
                           f"({', '.join(never[:3])})"),
                "counts": counts, "audited": audited}
    return {"status": "ok",
            "detail": (f"{len(declared)} screen(s) declared and audited, "
                       f"{counts['new'] + counts['changed']} awaiting a re-reaction"),
            "counts": counts, "audited": audited}


CAPABILITIES: list[dict] = [
    {
        "id": "polish",
        "what": "the polish audit (which screen looks cheap, and why)",
        "why": ("without it the team cannot tell a polished screen from a new "
                "feature, so every plan is free to add surface area instead of "
                "fixing what a player already feels"),
        "check": check_polish,
        "owner_approved": True,
    },
]


def review(project: Path, profile: dict | None = None,
           state: dict | None = None) -> list[dict]:
    """One row per capability: id, status, detail, what/why, owner_approved."""
    profile = profile if profile is not None else profile_of(project)
    state = state or {}
    rows = []
    for cap in CAPABILITIES:
        try:
            res = cap["check"](project, profile, state)
        except Exception as e:  # a broken check must be visible, never fatal
            res = {"status": "error", "detail": f"check failed: {e}"}
        rows.append({"id": cap["id"], "what": cap["what"], "why": cap["why"],
                     "owner_approved": bool(cap.get("owner_approved")),
                     **res})
    return rows


def unwired(project: Path, profile: dict | None = None,
            state: dict | None = None) -> list[dict]:
    return [r for r in review(project, profile, state)
            if r["status"] not in ("ok", "n/a")]


def summary_line(rows: list[dict]) -> str:
    bad = [r for r in rows if r["status"] not in ("ok", "n/a")]
    if not bad:
        return f"{len(rows)} capability check(s) wired"
    return (f"{len(bad)} of {len(rows)} team capabilit(y/ies) not wired: "
            + ", ".join(f"{r['id']} ({r['status']})" for r in bad))
